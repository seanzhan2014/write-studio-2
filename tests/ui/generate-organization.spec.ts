test("one-time generation executes its preparation and review choices without changing saved defaults", async ({ page, request }, info) => {
  test.setTimeout(90_000);
  const fake = await reviewModelServer();
  fake.control.mode = "clean";
  try {
    const provider = await (await request.post("/api/providers", { data: { name: "One-time generation", baseUrl: fake.baseUrl, secret: "fake-key" } })).json();
    const model = await (await request.post("/api/models", { data: { providerId: provider.id, name: "One-time generation", modelId: "one-time", maxInputCharacters: 120000 } })).json();
    const state = await (await request.get("/api/state")).json();
    const data = fullStudioFixture() as unknown as StudioData;
    Object.assign(data.settings, {generateModel: model.id, preparationMaxRounds:2, preparationRequireConfirmation:false});
    data.articles[0].aiGenerateSettings = normalizeAiGenerateOptions({ model: model.id, targetWords: 5000, tasks: { preparationMaxRounds: 2, reviewMaxRounds: 0, preparationRequireConfirmation: false } });
    expect((await request.put("/api/state", { headers: { "If-Match": String(state.revision) }, data: { data } })).ok()).toBeTruthy();
    await page.goto("/articles/article-main/outlines/outline-current/generate");
  await openGenerationPanels(page);
    await expect(page.getByRole("region", { name: "本次写作", exact: true })).toBeInViewport({ timeout: 20000 });
    await page.screenshot({ path: info.outputPath("generation-input.png") });
    await page.getByRole("combobox", { name: "参数调整范围", exact: true }).click();
    await page.getByRole("option", { name: "仅本次生成", exact: true }).click();
    await showTotalWordMode(page);
    await page.getByRole("textbox", { name: "正文目标字数", exact: true }).fill("700");
    await page.locator(".generate-command-card .writing-advanced > summary").click();
    const characters = page.getByRole("group", { name: /^人物表现/ });
    await characters.getByRole("textbox", { name: "心理展开方式", exact: true }).fill("只在关键决定处展开心理。");
    const workflow = page.locator(".generate-workflow-section .task-parameter-settings");
    if (await workflow.locator(":scope > summary").isVisible()) await workflow.locator(":scope > summary").click();
    await expect(workflow.getByText("聊天", { exact: true })).toHaveCount(0);
    await expect(workflow.getByText("插图模型", { exact: true })).toHaveCount(0);
    const preparation = workflow.locator(".task-parameter-group").filter({ has: page.locator("summary > span", { hasText: "写作准备" }) });
    await preparation.locator(":scope > summary").click();
    await preparation.getByLabel("写作前最多互动轮次", { exact: true }).fill("0");
    await preparation.getByLabel("准备稿无问题时仍需确认", { exact: true }).check();
    const review = workflow.locator(".task-parameter-group").filter({ has: page.locator("summary > span", { hasText: "自动审校" }) });
    await review.locator(":scope > summary").click();
    await review.getByLabel("最多修正次数", { exact: true }).fill("1");
    await review.getByLabel("本级审校规则", { exact: true }).fill("本次仅检查人物年龄，保留雨后场景。");
    const savedArticle = (await (await request.get("/api/state")).json()).data.articles[0];
    expect(savedArticle.aiGenerateSettings.targetWords).toBe(5000);
    expect(savedArticle.chapters[0].outlines.find((outline: { id: string }) => outline.id === "outline-current").generateOptions).toBeNull();
    await page.getByRole("button", { name: "开始生成", exact: true }).click();
    const interaction = page.locator(".task-interaction.inline");
    await expect(interaction.getByRole("button", { name: "确认准备稿并写正文", exact: true })).toBeVisible();
    await expect(interaction.getByLabel("生成进度").locator('[aria-current="step"]')).toContainText("待确认");
    await interaction.getByRole("button", { name: "确认准备稿并写正文", exact: true }).click();
    await expect.poll(async () => (await (await request.get("/api/ai/tasks")).json()).tasks[0]?.state, { timeout: 30000 }).toBe("success");
    const completed = (await (await request.get("/api/ai/tasks")).json()).tasks[0];
    expect(completed.contextOptions).toMatchObject({ targetWords: 700, reviewMaxRounds: 1, advanced: { psychology: "只在关键决定处展开心理。" }, writingPreparation: { maxRounds: 0, requireConfirmation: true } });
    expect(completed.contextOptions.reviewRuleSnapshot.rules[0].content).toBe("本次仅检查人物年龄，保留雨后场景。");
    expect(fake.control.calls.map(call => call.kind)).toEqual(["prepare", "generate", "review"]);
    expect(JSON.stringify(fake.control.calls.find(call => call.kind === "generate")?.body)).toContain("700");
    await page.reload();
    await showTotalWordMode(page);
    await expect(page.getByRole("textbox", { name: "正文目标字数", exact: true })).toHaveValue("5,000 字");
    await expect(interaction.getByLabel("生成进度").locator('[aria-current="step"]')).toContainText("完成");
    const finalArticle = (await (await request.get("/api/state")).json()).data.articles[0];
    expect(finalArticle.aiGenerateSettings.tasks.preparationMaxRounds).toBe(2);
    expect(finalArticle.aiGenerateSettings.tasks.reviewMaxRounds).toBe(0);
    expect(finalArticle.chapters[0].outlines.find((outline: { id: string }) => outline.id === "outline-current").generateOptions).toBeNull();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
    await page.screenshot({ path: info.outputPath("generation-organized.png"), fullPage: true });
  } finally { fake.close(); }
});

